    gsettings set org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:\$p10 command '/bin/true'
    gsettings set org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:\$p10 binding "\$block_bind_sw"
}

# ───────────────────────────────────────────────────────────────────────────────
# Harden Desktop UI (Limit Interaction)
# ───────────────────────────────────────────────────────────────────────────────

harden_desktop() {
    echo "\$(date -Iseconds) Hardening desktop UI elements" >> "\$LOG"
    
    # Disable Ubuntu Dock Extension (Robust method)
    gnome-extensions disable ubuntu-dock@ubuntu.com 2>/dev/null || true
    
    # Enable Hide Top Bar Extension
    gnome-extensions enable hidetopbar@mathieu.bidon.ca 2>/dev/null || true
    
    # Fallbacks via gsettings
    gsettings set org.gnome.desktop.interface enable-hot-corners false 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.dash-to-dock disable-overview-on-startup true 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.dash-to-dock autohide true 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.dash-to-dock dock-fixed false 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.dash-to-dock intellihide false 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.dash-to-dock height 0 2>/dev/null || true
    
    # Disable Desktop Icons (DING)
    gsettings set org.gnome.shell.extensions.ding show-home false 2>/dev/null || true
    gsettings set org.gnome.shell.extensions.ding show-trash false 2>/dev/null || true
    
    # GNOME Lockdown
    gsettings set org.gnome.desktop.lockdown disable-lock-screen true 2>/dev/null || true
    gsettings set org.gnome.desktop.lockdown disable-user-switching true 2>/dev/null || true
    gsettings set org.gnome.desktop.lockdown disable-log-out true 2>/dev/null || true
    
    # Restart Shell to apply changes (Required for some extensions/removals)
    # WARNING: On Wayland this terminates session. Kiosk usually runs on X11 or tolerates restart loop if config is idempotent.
    # We add a small delay and only run if session is established.
    (sleep 2; pkill -HUP gnome-shell) &
}

# ───────────────────────────────────────────────────────────────────────────────
# Prevent Screen Sleep
# ───────────────────────────────────────────────────────────────────────────────

prevent_sleep() {
    echo "\$(date -Iseconds) Disabling screen sleep" >> "\$LOG"
    xset s off 2>/dev/null || true
    xset -dpms 2>/dev/null || true
    xset s noblank 2>/dev/null || true
    gsettings set org.gnome.settings-daemon.plugins.power sleep-inactive-ac-type 'nothing' 2>/dev/null || true
    gsettings set org.gnome.settings-daemon.plugins.power sleep-inactive-battery-type 'nothing' 2>/dev/null || true
}

# ───────────────────────────────────────────────────────────────────────────────
# Main
# ───────────────────────────────────────────────────────────────────────────────

wait_for_gnome
connect_wifi
disable_shortcuts
block_keys
harden_desktop
setup_shortcuts
prevent_sleep

echo "\$(date -Iseconds) Kiosk setup complete" >> "\$LOG"
KIOSK_SCRIPT

    chmod +x "$autostart_path"
    debug "Autostart script created at $autostart_path"
}

# ═══════════════════════════════════════════════════════════════════════════════
# Kiosk Extensions Injection
# ═══════════════════════════════════════════════════════════════════════════════

_inject_kiosk_extensions() {
    local rootdir="$1"
    local extensions_dir="$rootdir/usr/share/gnome-shell/extensions"
    mkdir -p "$extensions_dir"
    
    info "Injecting GNOME Extensions..."
    
    # Install 'Hide Top Bar' from GitHub
    local ext_uuid="hidetopbar@mathieu.bidon.ca"
    local ext_path="$extensions_dir/$ext_uuid"
    
    if [ ! -d "$ext_path" ]; then
        info "Downloading Hide Top Bar extension..."
        local tmp_ext=$(mktemp -d)
        
        # Download master branch
        if wget -qO "$tmp_ext/extension.zip" "https://github.com/tuxor1337/hidetopbar/archive/refs/heads/master.zip"; then
            unzip -q "$tmp_ext/extension.zip" -d "$tmp_ext"
            
            # Dynamically find the extracted directory (e.g. hidetopbar-master)
            local src_dir=$(find "$tmp_ext" -mindepth 1 -maxdepth 1 -type d | head -n 1)
            
            if [ -n "$src_dir" ] && [ -d "$src_dir" ]; then
                mkdir -p "$ext_path"
                cp -r "$src_dir"/* "$ext_path/"
                
                # Compile Schemas
                if command -v glib-compile-schemas >/dev/null; then
                     info "Compiling schemas for $ext_uuid"
                     glib-compile-schemas "$ext_path/schemas" 2>/dev/null || warn "Failed to compile schemas for hidetopbar"
                else
                     warn "glib-compile-schemas not found - extension settings might fail"
                fi
                
                debug "Installed Hide Top Bar extension to $ext_path"
            else
                warn "Failed to extract Hide Top Bar (structure mismatch). Contents: $(ls "$tmp_ext")"
            fi
        else
            warn "Failed to download Hide Top Bar extension"
        fi
        
        rm -rf "$tmp_ext"
    else
        debug "Hide Top Bar extension already exists"
    fi
}

# ═══════════════════════════════════════════════════════════════════════════════
# Firefox Policies Injection
# ═══════════════════════════════════════════════════════════════════════════════

_inject_kiosk_policies() {
    local rootdir="$1"
    local policies_dir="$rootdir/usr/lib/firefox/distribution"
    mkdir -p "$policies_dir"
    
    local policies_file="$policies_dir/policies.json"
    info "Injecting Firefox policies..."
    
    cat > "$policies_file" <<POLICIES_JSON
{
    "policies": {
        "DisableAppUpdate": true,
        "DisableDeveloperTools": true,
        "DisableFormHistory": true,
        "DisablePasswordReveal": true,
        "DisablePocket": true,
        "DisablePrivateBrowsing": false,
        "DisableProfileImport": true,
        "DisableSystemAddonUpdate": true,
        "DisableTelemetry": true,
        "DNSOverHTTPS": {
            "Enabled": false
        },
        "DontCheckDefaultBrowser": true,
        "NoDefaultBookmarks": true,
        "OfferToSaveLogins": false,
        "OverrideFirstRunPage": "",
        "PasswordManagerEnabled": false,
        "Preferences": {
            "browser.tabs.warnOnClose": false,
            "browser.shell.checkDefaultBrowser": false,
            "browser.startup.homepage_override.mstone": "ignore",
            "datareporting.policy.dataSubmissionEnabled": false
        }
    }
}
POLICIES_JSON

    chmod 644 "$policies_file"
    debug "Firefox policies created at $policies_file"
}
